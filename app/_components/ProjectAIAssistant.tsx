function UserBubble({ text }: { text: string }) {
  return (
    <div className="flex justify-end">
      <div
        className="max-w-[85%] rounded-2xl px-3 py-2 text-[13px] leading-relaxed"
        style={{
          backgroundColor: BRAND_GREEN,
          color: "#fff",
          borderBottomRightRadius: 6,
        }}
      >
        {text}
      </div>
    </div>
  );
}

function AssistantBubble({
  text,
  fallback,
}: {
  text: string;
  fallback?: string;
}) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
    } catch {
      const el = document.createElement("textarea");
      el.value = text;
      el.style.position = "fixed";
      el.style.opacity = "0";
      document.body.appendChild(el);
      el.select();
      try {
        document.execCommand("copy");
      } catch {
        /* nothing more we can do */
      }
      el.remove();
    }
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };
  return (
    <div className="group flex items-start gap-2">
      <span
        aria-hidden
        className="mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-full"
        style={{ backgroundColor: BRAND_GREEN_SOFT, color: BRAND_GREEN }}
      >
        <Sparkles size={11} />
      </span>
      <div className="min-w-0 flex-1">
        <div
          className="rounded-2xl px-3 py-2"
          style={{
            backgroundColor: "color-mix(in srgb, var(--text) 6%, transparent)",
            color: "var(--text)",
            borderBottomLeftRadius: 6,
          }}
        >
          <div className="assistant-md">
            <ReactMarkdown remarkPlugins={[remarkGfm]}>{text}</ReactMarkdown>
          </div>
        </div>
        <div className="mt-1 flex items-center gap-2">
          <button
            type="button"
            onClick={() => void copy()}
            className="inline-flex items-center gap-1 text-[10px] opacity-0 transition-opacity group-hover:opacity-100 focus:opacity-100"
            style={{ color: copied ? BRAND_GREEN : "var(--text-faint)" }}
          >
            {copied ? <Check size={10} /> : <Copy size={10} />}
            {copied ? "Copied" : "Copy"}
          </button>
          {fallback && (
            <span
              className="text-[9px] tracking-wider uppercase"
              style={{ color: "var(--text-faint)" }}
            >
              {fallback === "no_key"
                ? "offline mode"
                : fallback === "openai_error"
                  ? "ai unreachable"
                  : fallback === "no_context"
                    ? "no project history yet"
                    : fallback}
            </span>
          )}
        </div>
      </div>
    </div>
  );
}

function AssistantThinking() {
  return (
    <div className="flex items-start gap-2">
      <span
        aria-hidden
        className="mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-full"
        style={{ backgroundColor: BRAND_GREEN_SOFT, color: BRAND_GREEN }}
      >
        <Sparkles size={11} />
      </span>
      <div
        className="rounded-2xl px-3 py-2 text-[13px] leading-relaxed"
        style={{
          backgroundColor: "color-mix(in srgb, var(--text) 6%, transparent)",
          color: "var(--text-muted)",
          borderBottomLeftRadius: 6,
        }}
      >
        <span
          className="inline-flex items-center gap-1"
          aria-label="Assistant is typing"
        >
          {[0, 1, 2].map((i) => (
            <span
              key={i}
              className="inline-block h-1.5 w-1.5 rounded-full"
              style={{
                backgroundColor: "var(--text-muted)",
                animation: "relay-typing 1.2s ease-in-out infinite",
                animationDelay: `${i * 0.18}s`,
              }}
            />
          ))}
        </span>
      </div>
    </div>
  );
}
